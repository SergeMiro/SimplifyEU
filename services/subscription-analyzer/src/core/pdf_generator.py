from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from io import BytesIO
from typing import List
from ..db.models import Analysis, AnalysisItem

def generate_pdf_report(analysis: Analysis, items: List[AnalysisItem]) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4)
    elements = []

    styles = getSampleStyleSheet()

    # Header
    elements.append(Paragraph("Subscription Analysis Report", styles['Title']))
    elements.append(Spacer(1, 12))

    # Summary
    summary_data = [
        ["Analysis ID", str(analysis.id)],
        ["Date", analysis.created_at.strftime("%Y-%m-%d")],
        ["Total Transactions", str(analysis.total_transactions or 0)],
        ["Subscriptions Found", str(analysis.subscriptions_found)],
        ["Potential Savings", f"€{analysis.potential_savings_eur:.2f}"]
    ]
    t_summary = Table(summary_data, hAlign='LEFT')
    t_summary.setStyle(TableStyle([
        ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold'),
        ('GRID', (0,0), (-1,-1), 1, colors.lightgrey),
        ('padding', (0,0), (-1,-1), 6),
    ]))
    elements.append(t_summary)
    elements.append(Spacer(1, 20))

    elements.append(Paragraph("Detected Subscriptions", styles['Heading2']))
    elements.append(Spacer(1, 10))

    # Items Table
    data = [['Merchant', 'Amount', 'Frequency', 'Conf.', 'Recommendation']]

    # Sort by confidence
    items_sorted = sorted(items, key=lambda x: x.confidence_score or 0, reverse=True)

    for item in items_sorted:
        # Wrap long text
        merchant = item.merchant_name or item.merchant_descriptor
        if len(merchant) > 20:
            merchant = merchant[:17] + "..."

        rec = item.recommendation or ""
        if len(rec) > 30:
            rec = rec[:27] + "..."

        data.append([
            merchant,
            f"€{item.amount_avg:.2f}",
            item.frequency,
            f"{int((item.confidence_score or 0)*100)}%",
            rec
        ])

    t = Table(data, colWidths=[120, 60, 70, 40, 150])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#2563eb')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 10),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
        ('BACKGROUND', (0, 1), (-1, -1), colors.beige),
        ('GRID', (0, 0), (-1, -1), 1, colors.white),
        ('FONTSIZE', (0, 1), (-1, -1), 9),
    ]))
    elements.append(t)

    # Footer
    elements.append(Spacer(1, 40))
    elements.append(Paragraph("Generated by SimplifyEU | GDPR compliant | Data deleted after 30 days", styles['Italic']))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
